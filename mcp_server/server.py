from __future__ import annotations

from typing import Annotated, Literal

from mcp.server import MCPServer
from pydantic import BaseModel, Field

from mcp_server.service import CalibrationService


class FeatureValues(BaseModel):
    confidence: float
    qpop: float
    gene_pop: float
    gene_coo: float


class FeatureCoverage(BaseModel):
    qpop: bool
    gene_pop: bool
    gene_coo: bool


class CalibrationResult(BaseModel):
    status: Literal["ok", "degraded"]
    model: str
    domain: str | None

    raw_confidence: float = Field(ge=0.0, le=1.0)
    fallback_score: float = Field(ge=0.0, le=1.0)

    calibrated_probability: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
    )
    threshold: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
    )

    decision: Literal["answer", "retrieve", "unknown"]
    artifact: str | None
    reason: str | None
    warnings: list[str]

    question_entity: str | None = None
    answer_entity: str | None = None
    feature_values: FeatureValues | None = None
    feature_coverage: FeatureCoverage | None = None
    noisy_entity: bool | None = None


service = CalibrationService()

mcp = MCPServer(
    "popular-but-wrong-calibrator",
    instructions=(
        "Calibrates confidence for supported entity-centric QA domains. "
        "The confidence input must be the arithmetic mean of generated "
        "answer-token probabilities, excluding special stop tokens."
    ),
)


@mcp.tool(
    name="calibrate",
    title="Calibrate answer confidence",
    structured_output=True,
)
def calibrate(
    question: Annotated[
        str,
        Field(
            min_length=1,
            description="Original factual question.",
        ),
    ],
    answer: Annotated[
        str,
        Field(
            description=(
                "Answer generated by the same model whose confidence "
                "is being calibrated."
            ),
        ),
    ],
    confidence: Annotated[
        float,
        Field(
            ge=0.0,
            le=1.0,
            description=(
                "Arithmetic mean of exp(token_logprob) over answer "
                "tokens, excluding special stop tokens."
            ),
        ),
    ],
    model: Annotated[
        str,
        Field(
            min_length=1,
            description=(
                "Artifact model slug, for example qwen2.5-7b."
            ),
        ),
    ],
    domain: Annotated[
        Literal["movies", "songs", "basketball"] | None,
        Field(
            description=(
                "QA domain. When omitted, the service attempts to "
                "infer it from the paper's question templates."
            ),
        ),
    ] = None,
) -> CalibrationResult:
    """Return calibrated correctness probability and routing decision."""

    result = service.calibrate(
        question=question,
        answer=answer,
        confidence=confidence,
        model=model,
        domain=domain,
    )

    return CalibrationResult.model_validate(result)


if __name__ == "__main__":
    mcp.run()